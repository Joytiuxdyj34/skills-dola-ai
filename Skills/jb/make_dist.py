#!/usr/bin/env python3
"""Build a clean distribution zip of LostHex-Skills.

Only what a recipient needs. Everything that is machine-specific, generated, or
internal to the author's setup is dropped, and a pre-flight scan fails the build if a
hardcoded personal path slipped back into a shipped file.

Usage:
    python scripts/make_dist.py                 # -> dist/LostHex-Skills-<date>.zip
    python scripts/make_dist.py --check         # report only, write nothing
    python scripts/make_dist.py --out FILE.zip
"""
import os
import re
import sys
import zipfile
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Never shipped. Directory names are matched at any depth.
EXCLUDE_DIRS = {
    ".git", ".wrangler", ".venv", "venv", "node_modules", "__pycache__",
    "dist", "site",        # generated by scripts/build_site.py
    "cfgit",               # the Cloudflare Workers git server, not part of the skills
}

# Never shipped. Filenames / globs at any depth.
EXCLUDE_FILES = [
    ".DS_Store", "Thumbs.db", "*.pyc", "*.log",
    "PUBLISH.md",          # the author's deployment notes
    "skills.bak-*",        # local backups
    "*.bak", "*.bak-*", "*.orig",
]

# Paths that must not appear in a shipped file. Only the resolved-user form counts:
# portable forms (%USERNAME%, ${WINUSER:-$USER}, $HOME) and documentation examples
# such as C:\Users\victim are fine, so the captured user segment is filtered below.
LEAK_PATTERNS = [
    re.compile(r"[A-Za-z]:\\Users\\([^\\\s\"'`]+)"),
    re.compile(r"/mnt/[a-z]/Users/([^/\s\"'`]+)"),
]

# Segments that are placeholders or documentation examples, not somebody's account.
ALLOW_USERS = {"victim", "suspect", "user", "username", "youruser", "you", "example", "public"}

TEXT_EXT = {".md", ".py", ".sh", ".bat", ".ps1", ".json", ".txt", ".yaml", ".yml"}


def excluded(name, patterns):
    for pat in patterns:
        if pat.startswith("*"):
            if name.endswith(pat[1:]):
                return True
        elif name == pat:
            return True
    return False


def collect():
    files = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS)
        for fn in sorted(filenames):
            if excluded(fn, EXCLUDE_FILES):
                continue
            full = os.path.join(dirpath, fn)
            files.append((full, os.path.relpath(full, ROOT).replace("\\", "/")))
    return files


def scan_leaks(files):
    hits = []
    for full, rel in files:
        if os.path.splitext(full)[1].lower() not in TEXT_EXT:
            continue
        try:
            text = open(full, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        for pat in LEAK_PATTERNS:
            for m in pat.finditer(text):
                seg = m.group(1)
                if any(c in seg for c in "$%{<"):
                    continue            # portable variable form
                if seg.lower() in ALLOW_USERS:
                    continue            # documentation example
                hits.append((rel, m.group(0)))
    return hits


def main():
    check = "--check" in sys.argv
    out = None
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
    out = out or os.path.join(ROOT, "dist", f"LostHex-Skills-{date.today():%Y%m%d}.zip")

    files = collect()
    total = sum(os.path.getsize(f) for f, _ in files)

    print(f"root        : {ROOT}")
    print(f"files       : {len(files)}")
    print(f"uncompressed: {total / 1024 / 1024:.1f} MB")
    print("excluded    : " + ", ".join(sorted(EXCLUDE_DIRS)))

    leaks = scan_leaks(files)
    if leaks:
        print(f"\n[FAIL] {len(leaks)} hardcoded personal path(s) in shipped files:")
        for rel, hit in leaks[:20]:
            print(f"  {rel}: {hit}")
        print("\nReplace with %USERPROFILE% / $HOME / wslpath, then rebuild.")
        return 1
    print("leak scan   : clean")

    if check:
        print("\n--check: nothing written")
        return 0

    os.makedirs(os.path.dirname(out), exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for full, rel in files:
            z.write(full, f"LostHex-Skills/{rel}")

    size = os.path.getsize(out)
    print(f"\nwrote       : {out}")
    print(f"zip size    : {size / 1024 / 1024:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
